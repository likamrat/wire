import test from "node:test";
import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import path from "node:path";
import { chromium, expect } from "@playwright/test";
import { createExportController } from "../../lib/export.mjs";
import { startServer } from "../../lib/server.mjs";
import { privateFixture, selectActivityOption, closeAnalyzeFilters } from "../support/helpers.mjs";
import { reviewRecords } from "../support/frontend-fixture.mjs";

test("packaged Analyze sections retain filtered results, focus and scroll on tab and browser return", { timeout: 60000 }, async t => {
    const all = reviewRecords(), records = [...all.slice(0, 24), all.at(-1)], cleanup = [];
    const { context } = await privateFixture({ after: fn => cleanup.push(fn) }, records);
    const server = await startServer(context, createExportController(context), { port: 0, frontend: "react", collector: { timers: false } });
    const browser = await chromium.launch();
    t.after(async () => { await browser.close(); await server.close(); for (const fn of cleanup.reverse()) await fn(); });
    const page = await browser.newPage({ viewport: { width: 1920, height: 1080 }, reducedMotion: "reduce" });
    const errors = [], reads = [];
    page.on("pageerror", e => errors.push(e.message));
    page.on("request", r => { if (r.url().endsWith("/api/snapshot")) reads.push(r.url()); });
    const nav = page.getByRole("navigation", { name: "Analyze sections", exact: true });
    const guide = nav.getByRole("button", { name: /Guide/ }), results = nav.getByRole("button", { name: "Results", exact: true });
    const commands = page.getByRole("group", { name: "Result scope and commands" }), scope = page.locator("#activityListSummary");
    const captures = process.env.WIRE_ANALYZE_HEADER_PROOFS;
    if (captures) await mkdir(captures, { recursive: true });
    const capture = async name => {
        if (captures) await page.screenshot({ path: path.join(captures, name + ".png"), animations: "disabled" });
    };
    await page.goto(server.url);
    await expect(guide).toBeVisible(); await page.evaluate(() => document.fonts.ready);
    await expect(results).toHaveAttribute("aria-current", "page");
    await capture("wide-results");
    await selectActivityOption(page, "outcomeFilter", ["failure"]); await closeAnalyzeFilters(page);
    await expect(scope).toContainText("5 matching tool calls");
    const ids = () => page.locator("#activityList .activity-card").evaluateAll(nodes => nodes.map(n => n.dataset.viewKey));
    const members = await ids(), filteredURL = page.url();
    assert.equal(members.length, 5);
    for (const [width, height, scale] of [[1920, 1080, 100], [390, 844, 200]]) {
        await page.setViewportSize({ width, height });
        await page.evaluate(n => { document.documentElement.style.fontSize = `${n}%`; window.scrollTo(0, 0); }, scale);
        await expect(commands.locator("#openAnalyzeFilters")).toContainText("1 filter applied");
        await capture(`${width}-filtered`);
        await page.evaluate(() => { window.scrollTo(0, 80); document.querySelector("#openChartReference").focus({ preventScroll: true }); });
        const beforeY = await page.evaluate(() => scrollY), beforeReads = reads.length;
        await page.keyboard.press("Enter");
        await expect(guide).toHaveAttribute("aria-current", "page"); await expect(guide).toBeFocused();
        await expect(page.locator("#chartReferenceExplanation")).toContainText("Outcome: Tool failed");
        await expect(commands).toBeHidden(); await expect(page.locator("#pageTitle")).toHaveText("Analyze");
        assert.equal(new URL(page.url()).searchParams.get("section"), "guide");
        assert.equal(new URL(page.url()).searchParams.has("result"), false);
        await capture(`${width}-guide`);
        await page.goBack(); await expect(results).toHaveAttribute("aria-current", "page"); await expect(guide).toBeFocused();
        assert.equal(page.url(), filteredURL); assert.equal(await page.evaluate(() => scrollY), beforeY);
        await page.goForward(); await expect(guide).toHaveAttribute("aria-current", "page");
        await results.press("Enter");
        await expect(results).toHaveAttribute("aria-current", "page"); await expect(guide).toBeFocused();
        assert.equal(page.url(), filteredURL); assert.equal(await page.evaluate(() => scrollY), beforeY);
        await expect(scope).toContainText("5 matching tool calls");
        assert.deepEqual(await ids(), members); assert.equal(reads.length, beforeReads);
        assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    }
    await page.goto(new URL("/?section=guide&result=failure", server.url).href);
    await expect(guide).toHaveAttribute("aria-current", "page"); await expect(page.locator("#chartReferenceShowData")).toBeEnabled();
    assert.deepEqual(errors, []);
});
