import test from "node:test";
import assert from "node:assert/strict";
import { readFile, readdir } from "node:fs/promises";
import path from "node:path";
import { createExportController } from "../lib/export.mjs";
import { loadBoardState, moveCard, replaceEvidence } from "../lib/store.mjs";
import { privateFixture, fixture } from "./helpers.mjs";

test("bulk snapshot export preserves every review label, source byte and prior bundle", async (t) => {
    const records = Array.from({ length: 36 }, (_, i) => fixture(`bulk-${i}`));
    const { context } = await privateFixture(t, records);
    await moveCard(context, "bulk-1", "reviewing");
    await moveCard(context, "bulk-2", "ready_to_export");
    const before = await loadBoardState(context);
    const sourcePath = path.join(context.dataDir, "private-evidence", before.evidenceFile);
    const original = await readFile(sourcePath);
    const stateFile = (await readdir(context.dataDir)).find((name) => name.endsWith(".state.json"));
    const stateBytes = await readFile(path.join(context.dataDir, stateFile));
    const controller = createExportController(context);
    const selection = { kind: "all", revision: before.revision };
    const options = { promptMode: "none", formats: ["html", "json", "markdown"] };
    const cancelled = await controller.preview("synthetic-bulk", undefined, options, selection);
    assert.equal(cancelled.records.length, 36);
    assert.equal(cancelled.snapshot.selectionScope.workIqActions, 36);
    assert.equal(cancelled.records[0].workflowStateAtPreview, "captured");
    assert.deepEqual(await readFile(path.join(context.dataDir, stateFile)), stateBytes);
    controller.cancel("synthetic-bulk", cancelled.previewId);
    assert.deepEqual(await readFile(path.join(context.dataDir, stateFile)), stateBytes);
    assert.deepEqual(await readdir(path.join(context.dataDir, "exports")), []);
    const draft = await controller.preview("synthetic-bulk", undefined, options, selection);
    await assert.rejects(controller.confirm("synthetic-bulk", draft.previewId, true), /disclosure review/);
    await assert.rejects(controller.review("different-owner", draft.previewId, true), /not found/);
    const reviewed = await controller.review("synthetic-bulk", draft.previewId, true);
    const committed = await controller.confirm("synthetic-bulk", draft.previewId, true);
    assert.deepEqual(committed.state.cards, before.cards);
    assert.equal(committed.state.evidenceFile, before.evidenceFile);
    assert.equal(committed.state.continuation, before.continuation);
    assert.equal(committed.state.revision, before.revision + 1);
    assert.equal(committed.state.exports.length, 1);
    for (const [name, content] of Object.entries(reviewed.files)) assert.equal(await readFile(committed.bundle.files[name], "utf8"), content);
    await assert.rejects(controller.confirm("synthetic-bulk", draft.previewId, true), /not found/);
    const another = await controller.preview("synthetic-bulk", undefined, options, { ...selection, revision: committed.state.revision });
    await controller.review("synthetic-bulk", another.previewId, true);
    await controller.confirm("synthetic-bulk", another.previewId, true);
    assert.equal((await loadBoardState(context)).exports.length, 2);
    for (const [name, content] of Object.entries(reviewed.files)) assert.equal(await readFile(committed.bundle.files[name], "utf8"), content);
    assert.deepEqual(await readFile(sourcePath), original);
});

test("invalid replacement, stale revision and changed classification require a new snapshot review", async (t) => {
    const { context } = await privateFixture(t);
    const state = await loadBoardState(context), controller = createExportController(context);
    const selection = { kind: "selected", revision: state.revision, scenarioIds: ["test-scenario"] };
    const preview = await controller.preview("synthetic", undefined, {}, selection);
    await controller.review("synthetic", preview.previewId, true);
    await assert.rejects(controller.preview("synthetic", undefined, { formats: [] }, selection), /format/);
    await assert.rejects(controller.confirm("synthetic", preview.previewId, true), /not found/);
    const invalidZone = await controller.preview("synthetic", undefined, {}, selection);
    await controller.review("synthetic", invalidZone.previewId, true);
    await assert.rejects(controller.confirm("synthetic", invalidZone.previewId, true, { timeZone: "invalid-zone" }), /Invalid report timezone/);
    await assert.rejects(controller.confirm("synthetic", invalidZone.previewId, true), /not found/);
    const fresh = await controller.preview("synthetic", undefined, {}, selection);
    await controller.review("synthetic", fresh.previewId, true);
    await moveCard(context, "test-scenario", "reviewing");
    await assert.rejects(controller.confirm("synthetic", fresh.previewId, true), /changed|expired/);
    await assert.rejects(controller.preview("synthetic", undefined, {}, selection), /changed/);
    assert.deepEqual(await readdir(path.join(context.dataDir, "exports")), []);
});

test("unrelated incoming collection data does not invalidate or expand a frozen reviewed All report", async (t) => {
    const { context } = await privateFixture(t);
    const state = await loadBoardState(context), controller = createExportController(context);
    const preview = await controller.preview("synthetic-live", undefined, { promptMode: "none", formats: ["json"] }, { kind: "all", revision: state.revision });
    await replaceEvidence(context, (records, importCoverage) => ({ records: [...records, fixture("incoming-synthetic")], importCoverage }));
    const reviewed = await controller.review("synthetic-live", preview.previewId, true);
    assert.equal(reviewed.records.length, 1);
    assert.equal(reviewed.files["product-report.json"], preview.files["product-report.json"]);
    await replaceEvidence(context, (records, importCoverage) => ({ records: [...records, fixture("another-incoming-synthetic")], importCoverage }));
    const committed = await controller.confirm("synthetic-live", preview.previewId, true);
    assert.equal(JSON.parse(await readFile(committed.bundle.files["product-report.json"], "utf8")).records.length, 1);
    assert.equal(committed.state.evidence.length, 3);
});
