import test from "node:test";
import assert from "node:assert/strict";
import { chromium, expect } from "@playwright/test";
import { fixture, privateFixture } from "./helpers.mjs";
import { startServer } from "../lib/server.mjs";
import { createExportController } from "../lib/export.mjs";
import { loadBoardState } from "../lib/store.mjs";

test("the failed-call link opens the right evidence from its touch edge and returns to the same card", async t => {
    const failed = fixture("lantern-failure"), completed = fixture("lantern-completed");
    failed.userPrompt.text = "Find the Lantern meeting.";
    completed.userPrompt.text = "Look up the Cedar launch.";
    Object.assign(failed.toolCalls[0], { toolSucceeded: false, reportedOutcome: "failed", apiResults: [] });
    const { context } = await privateFixture(t, [failed, completed]);
    const before = await loadBoardState(context);
    const runtime = await startServer(context, createExportController(context), { port: 0, collector: { timers: false } });
    t.after(() => runtime.close());
    const browser = await chromium.launch();
    t.after(() => browser.close());
    const page = await browser.newPage({ viewport: { width: 375, height: 900 }, hasTouch: true, reducedMotion: "reduce" });
    await page.goto(runtime.url);
    const link = page.getByRole("link", { name: "1 tool call failed", exact: true });
    const origin = page.url(), href = await link.getAttribute("href");
    assert.doesNotMatch(href, /lantern-failure|Lantern meeting/i);
    await link.scrollIntoViewIfNeeded();
    const box = await link.boundingBox();
    assert.ok(box.height >= 44 && box.width >= 44);
    await page.touchscreen.tap(box.x + box.width / 2, box.y + 2);
    const reader = page.getByRole("dialog", { name: "Interaction", exact: true });
    await expect(reader).toContainText(failed.userPrompt.text);
    await expect(reader).not.toContainText(completed.userPrompt.text);
    await expect(reader.getByRole("region", { name: "1 recorded call" })).toContainText("1 tool call failed");
    await expect(reader).toContainText("No failure reason was saved.");
    await page.goBack();
    await expect(page).toHaveURL(origin);
    await expect(reader).toBeHidden();
    await expect(link).toBeFocused();
    const after = await loadBoardState(context);
    for (const key of ["cards", "evidence", "exports"]) assert.deepEqual(after[key], before[key]);
});
